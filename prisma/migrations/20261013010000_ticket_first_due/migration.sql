-- الموعد الأصلي للتذكرة — لا يتبدّل بالتصعيد.
--
-- `stageDueAt` يُجدَّد عند كل تصعيد، فيُفقَد الموعد الذي حُدِّد لحظة
-- الرفع. وبدونه لا يُقاس التأخّر إلا استنتاجاً من المرحلة («إن صُعِّدت
-- فقد تأخّرت») — وهو استنتاجٌ هشّ: أيُّ مسٍّ للمرحلة يُفسد عمود
-- «متأخرة؟» في الإكسل، وهذا بعينه ما وقع في عطب الكنس.
ALTER TABLE "Ticket" ADD COLUMN "firstDueAt" TIMESTAMP(3);

-- التذاكر القائمة: مرحلتها الأولى كانت دائماً يومين من الرفع
-- (TICKET_STAGE_DAYS = 2)، فيُحسب موعدها الأصلي من تاريخ رفعها. ولا
-- يُخترَع تاريخٌ لغيرها: ما لا يُحسَب يبقى NULL ويعود للاستنتاج القديم.
UPDATE "Ticket" SET "firstDueAt" = "createdAt" + INTERVAL '2 days';
