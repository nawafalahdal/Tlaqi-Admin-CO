-- فصلُ «حجزِ الإرسال» عن «ختمِ القبول».
--
-- كان `welcomeEmailSentAt` يُكتَب قبل الإرسال ليُحجَز الحقُّ مرّةً واحدة،
-- ثم يُمسَح إن أخفق البريد. وبينهما نداءٌ شبكيٌّ قد يَطول — فإن انقطع
-- التنفيذُ هناك بقي الختمُ مكتوباً بلا رسالةٍ أُرسلت: فالشيتُ يقول
-- «✓ وصلت»، وزرُّ الإرسال يُردّ بـ«أُرسلت من قبل» إلى الأبد.
--
-- فصار الحجزُ في عمودٍ خاصٍّ له مهلة، و`welcomeEmailSentAt` لا يُكتَب
-- إلا بعد قبول المزوّد.
--
-- وما مضى لا يُمَسّ: من كُتب له ختمٌ سابقاً يبقى كما هو — قد تكون
-- بطاقتُه وصلت فعلاً، ومسحُه يُرسل نسخةً ثانيةً لمن قرأ الأولى.
-- ولا حذفَ هنا ولا تغييرَ عمودٍ قائم.

ALTER TABLE "User"   ADD COLUMN IF NOT EXISTS "welcomeClaimedAt" TIMESTAMP(3);
ALTER TABLE "Member" ADD COLUMN IF NOT EXISTS "welcomeClaimedAt" TIMESTAMP(3);
