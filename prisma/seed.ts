async function upsertTrack(
  scope: "department_member" | "department_admin" | "operations_officer" | "executive",
  departmentId: string | null,
  questions: Q[]
) {
  // ملاحظة: Postgres يعامل NULL كقيمة مميزة دائماً في قيود التفرّد، فلا يصلح
  // الاعتماد على upsert المركّب (scope, departmentId) عندما تكون departmentId
  // فارغة (مسارات القادة/التنفيذيين) — نبحث يدوياً بدلاً من ذلك في تلك الحالة.
  const track = departmentId
    ? await prisma.testTrack.upsert({
        where: { scope_departmentId: { scope, departmentId } },
        update: {},
        create: { scope, departmentId },
      })
    : (await prisma.testTrack.findFirst({ where: { scope } })) ??
      (await prisma.testTrack.create({ data: { scope, departmentId: null } }));

  const existing = await prisma.testQuestion.count({ where: { trackId: track.id } });
  if (existing === 0) {
    await prisma.testQuestion.createMany({
      data: questions.map((q, i) => ({
        trackId: track.id,
        prompt: q.prompt,
        options: q.options,
        correctIndex: q.correctIndex,
        order: i,
      })),
    });
  }
  return track;
}

