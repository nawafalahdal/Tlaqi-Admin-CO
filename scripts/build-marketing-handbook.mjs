/** صورةٌ من الدليل بوصفها المسجّل — وما لم يُلتقط يُذكر ولا يُخترع.
 *  لقطاتُ الصفحة كاملةً (عرض 1440) تُقصّ عنها قائمةُ المنصة الجانبية فيكبر محتوى الوكيل في الصفحة،
 *  إلا ما طُلبت فيه القائمة (`nav`) ليُرى موضعُ «وكيل التسويق» فيها. و`crop` قصٌّ صريحٌ لصورةٍ بعينها. */
async function fig(file, { wide = false, tall = false, nav = false, crop } = {}) {
  const m = byFile.get(file);
  if (!m) {
    missing.push(file);
    return `<p class="note">صورة «${esc(file)}» غير متاحة في هذا الإصدار.</p>`;
  }
  const out = path.join(TMP, file.replace(/\.png$/, ".jpg"));
  let img = sharp(path.join(SHOTS, file));
  const meta = await img.metadata();
  if (crop) img = img.extract(crop);
  else if (!nav && meta.width === 1440) img = img.extract({ left: 0, top: 0, width: 1160, height: meta.height });
  await img.resize({ width: wide ? 1700 : 1500, withoutEnlargement: true }).jpeg({ quality: 80, mozjpeg: true }).toFile(out);
  used.push(file);
  figNo += 1;
  return `<figure class="${tall ? "tall" : ""}"><img src="${url(out)}" alt=""><figcaption><b>صورة ${figNo} — ${esc(m.action)}</b><span>${esc(m.role)}: ${esc(m.observe)}</span></figcaption></figure>`;
}

