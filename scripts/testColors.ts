import { randomInt } from "node:crypto";

/** **لونٌ فريدٌ لقسم فحص.** منذ إصلاح ألوان الأقسام (نوفمبر 2026) لا يتشارك قسمان لوناً، ولو كان أحدهما مؤرشفاً.
 *  فالفحوصُ القديمة التي أنشأت أقساماً بألوان الأقسام الرسمية (#C34900، #67C090…) صارت تُرفض بحقّ. وهذا تغييرٌ في
 *  تهيئة الفحص لا في توقّعه: ما يُختبر (الحذف، الأرشفة، اللجان، الهيكل) هو نفسه، باللون الفريد بدل المكرَّر. */
export function uniqueTestColor(): string {
  return `#${randomInt(0, 0xffffff).toString(16).padStart(6, "0").toUpperCase()}`;
}
