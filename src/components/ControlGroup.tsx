import type { CSSProperties, ReactNode } from "react";

/** شريطُ أدواتٍ واحدٌ يَضمّ اللغةَ والسمةَ و«تحسين».
 *
 *  ## العطبُ الذي يُصلحه، كما رُئي في لقطة الشاشة
 *
 *  كانت الأزرارُ الثلاثةُ مستقلّةً، فجاءت كأنها من ثلاثة تطبيقات: زرُّ
 *  اللغة مستطيلٌ بزوايا صغيرة، ومفتاحُ السمة قرصٌ أطولُ منه، وبينهما
 *  فجوةٌ لا قاعدةَ لها — وكلٌّ بحدٍّ وارتفاعٍ ونصفِ قطرٍ يَخصّه. والعينُ
 *  تَقرأ ذلك إهمالاً لا تصميماً.
 *
 *  فصارت في **إطارٍ واحد**: حدٌّ واحدٌ يَلفّها، وارتفاعٌ واحدٌ لكلِّها،
 *  وفواصلُ شعريّةٌ بينها بدل الفجوات. فتُقرأ مجموعةً واحدةً من أدوات
 *  الشاشة — وهي كذلك فعلاً.
 *
 *  ## والقياساتُ ليست ذوقاً
 *
 *  الارتفاعُ ٤٤ بكسلاً: هو أصغرُ هدفٍ يُصيبه الإبهامُ على الجوّال بلا
 *  خطأ، وهو ما توصي به معاييرُ الوصول. وكانت الأزرارُ ٣٢ بكسلاً فكان
 *  النقرُ عليها على الجوّال رمياً.
 *
 *  ويَتلوّن بلون الترويسة التي يسكنها عبر متغيّرٍ واحد (`--ctl`)،
 *  فلا يشذّ عن قسمٍ ولا سمة — ويُشتَقّ منه الحدُّ والسطحُ والفاصل.
 */
export function ControlGroup({
  color,
  label,
  children,
  className = "",
}: {
  /** لونُ الترويسة — تُشتَقّ منه بقيّةُ الطبقات */
  color: string;
  /** اسمُ المجموعة للقارئ الآليّ — من قاموس اللغة (`ui.displayTools`) */
  label: string;
  children: ReactNode;
  className?: string;
}) {
  return (
    <div
      className={`ctl-group ${className}`.trim()}
      style={{ "--ctl": color } as CSSProperties}
      // مجموعةُ أدواتٍ لا شريطُ تنقّل: يُعلَن دورُها للقارئ الآليّ
      role="group"
      aria-label={label}
    >
      {children}
    </div>
  );
}

/** فاصلٌ شعريٌّ بين أداتين — زينةٌ تُخفى عن القارئ الآليّ */
export function ControlDivider() {
  return <span aria-hidden className="ctl-group__sep" />;
}
