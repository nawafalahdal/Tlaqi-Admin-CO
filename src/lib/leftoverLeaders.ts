import { prisma } from "@/lib/prisma";

/** بقايا قادةٍ حُذفت حساباتُهم الإدارية قبل أن يصير الحذفُ النهائيُّ للسجلَّين معاً.
 *
 *  تُعرَف بثلاثٍ معاً، ولا تُخمَّن:
 *  - سجلُّ ترشّحٍ قياديٍّ معتمَد (دُعي صاحبُه لمنصبٍ لا لعضوية)،
 *  - كلمةُ مروره فارغة — فالحسابُ الإداريُّ يأخذها عند الاعتماد ويُفرِّغها من السجلّ
 *    (ومن اعتُمد قبل 6 أكتوبر لم تكن على سجلّه كلمةٌ أصلاً، فيُعرَف كذلك)،
 *  - ولا حسابَ إداريَّ اليوم بالبريد نفسه — فقد أُنشئ ثم حُذف.
 *
 *  فلا يدخل فيها **من أُعيدت دعوتُه** (الدعوةُ لا تُقبل ما بقي للبريد سجلّ، فله سجلٌّ
 *  جديدٌ بدعوةٍ جديدة، وحسابٌ إداريٌّ إن اعتُمد قائداً)، ولا من تعثّر اعتمادُه فلم
 *  يُنشأ حسابُه (كلمةُ مروره باقية)، ولا المُنحّى (حسابُه باقٍ وإن لم يُدخِل).
 *
 *  والاستثناءُ الوحيد المعروف: قائدٌ قائمٌ غُيِّر بريدُ حسابه قبل 13 أكتوبر (قبل أن يصير
 *  التغييرُ للسجلَّين) فبقي سجلُّه على البريد القديم — لا يُغلَق به أحد، لكن صفحةَ
 *  الأعضاء تُنبّه بالاسم قبل محوه. */
export async function leftoverLeaderIds(): Promise<Set<string>> {
  const rows = await prisma.member.findMany({
    where: { approvalStatus: "approved", passwordHash: null, invite: { targetRole: { not: "member" } } },
    select: { id: true, email: true },
  });
  if (rows.length === 0) return new Set();
  const held = new Set(
    (await prisma.user.findMany({ where: { email: { in: rows.map((r) => r.email) } }, select: { email: true } })).map((u) => u.email)
  );
  return new Set(rows.filter((r) => !held.has(r.email)).map((r) => r.id));
}
