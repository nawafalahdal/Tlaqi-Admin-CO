/** **قيادةُ اللجنة ليست قيادةَ قسم — والحسابُ القياديُّ القديم على لجنةٍ مجمَّد.**
 *
 *  في النظام الأول كان قائدُ اللجنة حساباً إدارياً (`department_admin`) قسمُه اللجنة.
 *  والدورُ نفسُه دورُ قائد القسم، ويُفحص في عشرات المواضع — بعضُها يكتفي بالدور وحده
 *  (التوقيع، والإعلانات، ومسارات الاعتماد، والخلافة). فإبقاؤه يُبقي صلاحياتِ قائد القسم
 *  داخل اللجنة وخارجها.
 *
 *  فيُجمَّد من لحظة النشر، قبل أي ترحيل: لا دخولَ به، وجلستُه تُبطَل في الطلب التالي،
 *  وطبقةُ الهيكل لا تمنحه شيئاً. ثم يُحوَّل إلى عضويةٍ في القسم الأصيل وقيادةٍ للجنة
 *  (`legacyConversion`) بقرار المؤسس. وانظر `docs/TLAQI_COMMITTEE_LEAD_SEPARATION_PLAN_AR.md`. */
export function isCommitteeScopedLeader(u: {
  role: string;
  department?: { parentId: string | null } | null;
}): boolean {
  return u.role === "department_admin" && !!u.department?.parentId;
}

