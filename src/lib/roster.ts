/** من هو «العضو» في قوائم الأعضاء.
 *
 *  **العطبُ الذي يُصلحه هذا الشرط:** المرشّحُ القيادي (رئيسٌ تنفيذي،
 *  مسؤول متابعة وتشغيل، قائدُ قسم) يمرّ بالطريق نفسه الذي يمرّ به العضو
 *  — صفٌّ في `Member`، ثم اختبار، ثم اعتماد — وعند اعتماده يُنشأ له حسابٌ
 *  إداريٌّ في `User`. لكنّ صفَّه المرشّح يبقى `approved` و`isActive`،
 *  وهما وحدهما ما كانت القوائم تسأل عنه. فظهر الرئيس التنفيذي عضواً
 *  عادياً في قائمة أعضائه هو، وظهر كلُّ قائدٍ مرّتين في قسمه: قائداً
 *  وعضواً — ووصلته شهادةُ «ثلاثة أشهر عضواً» وهو لم يكن عضواً قط.
 *
 *  والتصنيفُ محفوظٌ أصلاً لا يُستنتَج: الدعوة تقول لأيّ منصبٍ صدرت
 *  (`invite.targetRole`). فالعضو من دُعي عضواً — لا من وُجد له صفّ.
 *  ولا يُمَسّ صفُّ المرشّح نفسه: هو سجلُّ اختباره واعتماده، ويُقرأ في
 *  دورة الحياة وفي الشيت.
 *
 *  **يُمرَّر على كل قائمةٍ تَعرض أعضاءً أو تَعدّهم أو تُراسلهم بصفتهم
 *  أعضاء** — ويحرسه فحصُ بناءٍ (`check-member-roster`). */
export const ROSTER_MEMBER_WHERE = {
  isActive: true,
  approvalStatus: "approved" as const,
  invite: { targetRole: "member" as const },
};

/** الصيغةُ نفسها لما جُلب ثم يُقسَم في الذاكرة. */
export function isRosterMember(m: {
  isActive: boolean;
  approvalStatus: string;
  invite: { targetRole: string };
}): boolean {
  return m.isActive && m.approvalStatus === "approved" && m.invite.targetRole === "member";
}
